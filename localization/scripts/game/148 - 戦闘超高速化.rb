#------------------------------------------------------------------------------
# 戦闘時の処理速度を超高速化します。
# 押したボタンによって挙動の違う高速化が行われます。
# それぞれ以下のようになります。
# 
# Lボタン(Qキー)         : 処理のみ高速化
# CTRLキー               : 処理とアニメーションを高速化
# Aボタン(SHIFTキー)     : アニメーションのみ高速化
#==============================================================================
module BATTLE_S_UP
  
  #高速化を無効化するスイッチを指定。
  
  SW = 1000
  
  #戦闘超高速化ボタン1を設定します。
  #こちらでは、処理は高速化されますがアニメーション速度は変更しません。
  #無効にしたい場合は配列を空（[]という風に、中身を消す）にして下さい。
  #複数設定したい場合は、ヘルプをInputで検索し
  #下部にある定数の項目から、設定したいボタンを選び、「,」で区切って
  #配列内に追加して下さい。
  
  KEY1 = [:L]
  
  #戦闘超高速化ボタン2を設定します。
  #こちらでは、処理もアニメーション速度も変更されます。
  #無効にしたい場合は配列を空（[]という風に、中身を消す）にして下さい。
  #複数設定したい場合は、ヘルプをInputで検索し
  #下部にある定数の項目から、設定したいボタンを選び、「,」で区切って
  #配列内に追加して下さい。
  
  KEY2 = [:CTRL]
  
  #戦闘超高速化ボタン3を設定します。
  #こちらでは、処理を高速化せずアニメーション速度のみ変更されます。
  #無効にしたい場合は配列を空（[]という風に、中身を消す）にして下さい。
  #複数設定したい場合は、ヘルプをInputで検索し
  #下部にある定数の項目から、設定したいボタンを選び、「,」で区切って
  #配列内に追加して下さい。
  
  KEY3 = [:A]
  
  #アニメーション速度高速化時の倍率を設定します。(数字が大きいほど高速化)
  
  ASPD = 4
  
  #高速化中のアニメーション・エフェクトウェイトを設定します。(数字が小さいほど高速化)
  
  WAIT = 1
  
  #高速化中のウェイト割合を設定します。数字が小さいほど短縮。(必ず1以上)
  
  WAIR1 = 1
  
  #高速化中の強制ウェイト割合を設定します。数字が小さいほど短縮。(必ず1以上)
  
  WAIR2 = 20
  
  #戦闘終了後のリザルト処理中も有効にするかどうかを設定します。
  #trueで有効。falseで無効。
  #なお、デフォルトのリザルトでは特に意味はないと思います。
  
  Result = true
  
  #テストモードのみ有効にするかどうかを設定します。
  #true:テストモードのみ/false:限定しない
  
  TEST = false
  
  #以下変更不要。
  
  #全高速化ボタンを取得。
  
  KEYALL = [KEY1,KEY2,KEY3]
  
  #--------------------------------------------------------------------------
  # 高速化ボタンが押されているかを判定
  #--------------------------------------------------------------------------
  def self.key(type)
    !$game_switches[SW] && KEYALL[type].any? {|k| Input.press?(k)} && (Result ? true : !BattleManager.phase_nil?)
  end
end
module BattleManager
  #--------------------------------------------------------------------------
  # フェーズがnilかどうかを判定。
  #--------------------------------------------------------------------------
  def self.phase_nil?
    @phase == nil
  end
end
