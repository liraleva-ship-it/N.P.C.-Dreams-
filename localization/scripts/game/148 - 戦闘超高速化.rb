class Sprite_Base < Sprite
  #--------------------------------------------------------------------------
  # アニメーションの更新
  #--------------------------------------------------------------------------
  alias update_animation_speedup update_animation
  def update_animation
    n = $game_party.in_battle && $game_troop.show_fast_extra2? ? BATTLE_S_UP::ASPD : 1
    n = 1 if n < 1
    n.times {update_animation_speedup}
  end
end
class Scene_Battle < Scene_Base
  #--------------------------------------------------------------------------
  # アニメーション表示が終わるまでウェイト
  #--------------------------------------------------------------------------
  alias wait_for_animation_speedup wait_for_animation
  def wait_for_animation
    $game_troop.show_fast_extra1? ? wait(BATTLE_S_UP::WAIT) : wait_for_animation_speedup
  end
  #--------------------------------------------------------------------------
  # エフェクト実行が終わるまでウェイト
  #--------------------------------------------------------------------------
  alias wait_for_effect_speedup wait_for_effect
  def wait_for_effect
    $game_troop.show_fast_extra1? ? wait(BATTLE_S_UP::WAIT) : wait_for_effect_speedup
  end
  #--------------------------------------------------------------------------
  # ウェイト
  #--------------------------------------------------------------------------
  alias wait_speedup wait
  def wait(duration)
    t = $game_troop.show_fast_extra1? ? (duration / (100.0 / BATTLE_S_UP::WAIR1)).to_i : duration
    t = 1 if t < 1 && duration > 0
    wait_speedup(t)
  end
  #--------------------------------------------------------------------------
  # 短時間ウェイト（早送り無効）
  #--------------------------------------------------------------------------
  alias abs_wait_speedup abs_wait
  def abs_wait(duration)
    t = $game_troop.show_fast_extra1? ? (duration / (100.0 / BATTLE_S_UP::WAIR2)).to_i : duration
    t = 1 if t < 1 && duration > 0
    abs_wait_speedup(t)
  end
end
class Game_Troop < Game_Unit
  #--------------------------------------------------------------------------
  # 超高速化判定1
  #--------------------------------------------------------------------------
  def show_fast_extra1?
    show_fast_extra_flag1 or show_fast_extra_flag2
  end
  #--------------------------------------------------------------------------
  # 超高速化判定2
  #--------------------------------------------------------------------------
  def show_fast_extra2?
    show_fast_extra_flag2 or show_fast_extra_flag3
  end
  #--------------------------------------------------------------------------
  # 高速表示フラグ1
  #--------------------------------------------------------------------------
  def show_fast_extra_flag1
    BATTLE_S_UP.key(0)
  end
  #--------------------------------------------------------------------------
  # 高速表示フラグ2
  #--------------------------------------------------------------------------
  def show_fast_extra_flag2
    BATTLE_S_UP.key(1)
  end
  #--------------------------------------------------------------------------
  # 高速表示フラグ3
  #--------------------------------------------------------------------------
  def show_fast_extra_flag3
    BATTLE_S_UP.key(2)
  end
end
