#------------------------------------------------------------------------------
# party_preserve_gold
# 
# 所持金を保存します。
#------------------------------------------------------------------------------
# party_preserve_actors
# 
# 現在のメンバーを保存します。
#------------------------------------------------------------------------------
# party_preserve_item
# 
# 現在のアイテムを保存します。
#------------------------------------------------------------------------------
# party_preserve_weapon
# 
# 現在の武器を保存します。
#------------------------------------------------------------------------------
# party_preserve_armor
# 
# 現在の防具を保存します。
#------------------------------------------------------------------------------
