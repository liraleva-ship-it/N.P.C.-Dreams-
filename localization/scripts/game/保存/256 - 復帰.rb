class Game_Party < Game_Unit
  #--------------------------------------------------------------------------
  # 所持金保存
  #--------------------------------------------------------------------------
  def party_preserve_gold
    party_preserve_gold_data(@gold)
  end
  #--------------------------------------------------------------------------
  # 現在のメンバー保存
  #--------------------------------------------------------------------------
  def party_preserve_actors
    party_preserve_actors_data(@actors)
  end
  #--------------------------------------------------------------------------
  # 現在のアイテム保存
  #--------------------------------------------------------------------------
  def party_preserve_item
    party_preserve_item_data(@items)
  end
  
  def party_nil_item
    party_nil_item_data(@items)
  end
  #--------------------------------------------------------------------------
  # 現在の武器保存
  #--------------------------------------------------------------------------
  def party_preserve_weapon
    party_preserve_weapon_data(@weapons)
  end
  #--------------------------------------------------------------------------
  # 現在の防具保存
  #--------------------------------------------------------------------------
  def party_preserve_armor
    party_preserve_armor_data(@armors)
  end
  #--------------------------------------------------------------------------
  # 所持金復帰
  #--------------------------------------------------------------------------
  def party_reverse_gold
    @gold = party_preserve_gold_data
  end
  #--------------------------------------------------------------------------
  # アクター復帰
  #--------------------------------------------------------------------------
  def party_reverse_actors
    @actors = party_preserve_actors_data.clone
  end
  #--------------------------------------------------------------------------
  # アイテム復帰
  #--------------------------------------------------------------------------
  def party_reverse_item
    @items = party_preserve_item_data.clone
  end
  #--------------------------------------------------------------------------
  # 武器復帰
  #--------------------------------------------------------------------------
  def party_reverse_weapon
    @weapons = party_preserve_weapon_data.clone
  end
  #--------------------------------------------------------------------------
  # 防具復帰
  #--------------------------------------------------------------------------
  def party_reverse_armor
    @armors = party_preserve_armor_data.clone
  end
  #--------------------------------------------------------------------------
  # 所持金データ
  #--------------------------------------------------------------------------
  def party_preserve_gold_data(data = nil)
    @party_preserve_gold_data = 0 if @party_preserve_gold_data == nil
    @party_preserve_gold_data = data if data != nil
    @party_preserve_gold_data
  end
  #--------------------------------------------------------------------------
  # メンバーデータ
  #--------------------------------------------------------------------------
  def party_preserve_actors_data(data = nil)
    @party_preserve_actors_data = [] if @party_preserve_actors_data == nil
    @party_preserve_actors_data = data.clone if data != nil
    @party_preserve_actors_data
  end
  #--------------------------------------------------------------------------
  # アイテムデータ
  #--------------------------------------------------------------------------
  def party_preserve_item_data(data = nil)
    @party_preserve_item_data = {} if @party_preserve_item_data == nil
    @party_preserve_item_data = data.clone if data != nil
    @party_preserve_item_data
  end

 def party_nil_item_data(data = nil)
    @party_preserve_item_data = {} if @party_preserve_item_data == nil
    @party_preserve_item_data = {} if data != nil
    @party_preserve_item_data
  end

  #--------------------------------------------------------------------------
  # 武器データ
  #--------------------------------------------------------------------------
  def party_preserve_weapon_data(data = nil)
    @party_preserve_weapon_data = {} if @party_preserve_weapon_data == nil
    @party_preserve_weapon_data = data.clone if data != nil
    @party_preserve_weapon_data
  end
  #--------------------------------------------------------------------------
  # 防具データ
  #--------------------------------------------------------------------------
  def party_preserve_armor_data(data = nil)
    @party_preserve_armor_data = {} if @party_preserve_armor_data == nil
    @party_preserve_armor_data = data.clone if data != nil
    @party_preserve_armor_data
  end
end
class Game_Actor
  #--------------------------------------------------------------------------
  # アクター保存
  #--------------------------------------------------------------------------
  def actor_preserve
    return if !PRESERVE_CONDITION::ACTOR_NAME_EMPTY && $data_actors[id].name.empty?
    @actor_preserve_data = {:exp => {}, :param_plus => [0] * 8,:skills => [],:equips => []}
    @actor_preserve_data[:exp] = @exp.clone
    @actor_preserve_data[:param_plus] = @param_plus.clone
    @actor_preserve_data[:skills] = @skills.clone
    @equips.each {|i| @actor_preserve_data[:equips].push(i.clone)}
  end
  #--------------------------------------------------------------------------
  # アクター復帰
  #--------------------------------------------------------------------------
  def actor_reverse
    return if @actor_preserve_data == nil
    @exp = @actor_preserve_data[:exp].clone
    @param_plus = @actor_preserve_data[:param_plus].clone
    @skills = @actor_preserve_data[:skills].clone
    @equips.each_index {|i| @equips[i] = @actor_preserve_data[:equips][i].clone}
    change_exp(exp, false)
  end
end