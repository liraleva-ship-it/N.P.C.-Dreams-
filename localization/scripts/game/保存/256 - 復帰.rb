#
# param_preserve    (能力強化の保存)
# 
# 現在のID1のアクターのEXP・能力強化・スキル・装備を保存します。
#------------------------------------------------------------------------------
# party_preserve_all_item
# 
# 現在のアイテム・武器・防具を保存します。
#------------------------------------------------------------------------------
# all_actor_preserve
# 
# 現在の全アクターのEXP・能力強化・スキル・装備を保存します。
#------------------------------------------------------------------------------
# party_reverse_gold
# 
# 所持金を保存時の状態に戻します。
# 保存されていない場合は初期化されます。
#------------------------------------------------------------------------------
# party_reverse_actors
# 
# 現在のメンバーを保存時の状態に戻します。
# 保存されていない場合はメンバーが存在しない状態になります。
#------------------------------------------------------------------------------
# party_reverse_item
# 
# 現在のアイテムを保存時の状態に戻します。
# 保存されていない場合は初期化されます。
#------------------------------------------------------------------------------
# party_reverse_weapon
# 
# 現在の武器を保存時の状態に戻します。
# 保存されていない場合は初期化されます。
#------------------------------------------------------------------------------
# party_reverse_armor
# 
# 現在の防具を保存時の状態に戻します。
# 保存されていない場合は初期化されます。
#------------------------------------------------------------------------------
# actor_reverse(1)
#
# param_reverse　(能力強化戻す)
# 
# 現在のID1のアクターのEXP・能力強化・スキル・装備を保存時の状態に戻します。
# 保存されていないアクターには無効です。
#------------------------------------------------------------------------------
# party_reverse_all_item
# 
# 現在のアイテム・武器・防具を保存時の状態に戻します。
# 保存されていない場合は初期化されます。
#------------------------------------------------------------------------------
# all_actor_reverse
# 
# 現在の全アクターのEXP・能力強化・スキル・装備を保存時の状態に戻します。
# 保存されていないアクターには無効です。
#------------------------------------------------------------------------------
