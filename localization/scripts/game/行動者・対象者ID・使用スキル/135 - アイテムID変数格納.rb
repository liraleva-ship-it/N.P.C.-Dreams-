class RPG::BaseItem
  #--------------------------------------------------------------------------
  # 変数を格納するアイテム/スキルか？
  #--------------------------------------------------------------------------
  def variables_get_is?
    (@variables_get_is ||= ((@note.include?(SELF_AND_TARGET::WORD) or SELF_AND_TARGET::ALL) ? 1 : 0)) == 1
  end
end