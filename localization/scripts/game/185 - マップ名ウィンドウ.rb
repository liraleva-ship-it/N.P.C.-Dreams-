# 　メニュー画面の処理を行うクラスです。
#==============================================================================

class Scene_Menu < Scene_MenuBase
  #--------------------------------------------------------------------------
  # ● 開始処理
  #--------------------------------------------------------------------------
  alias m_start start
  def start
    m_start
    create_map_window
  end
  #--------------------------------------------------------------------------
  # ● マップウィンドウの作成
  #--------------------------------------------------------------------------
  def create_map_window
    @map_window = Window_Mapname.new
    @map_window.x = 0
    @map_window.y = Graphics.height - @gold_window.height - @map_window.height
  end
end