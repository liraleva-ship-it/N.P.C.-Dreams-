#==============================================================================
# ■ Window_Mapname
#------------------------------------------------------------------------------
# 　マップ名を表示するウィンドウです。
#==============================================================================


class Window_Mapname < Window_Selectable
  #--------------------------------------------------------------------------
  # ● オブジェクト初期化
  #--------------------------------------------------------------------------
  def initialize
    super(0,0, window_width, fitting_height(2))
    refresh
  end
  #--------------------------------------------------------------------------
  # ● ウィンドウ幅の取得
  #--------------------------------------------------------------------------
  def window_width
    return 160
  end
  #--------------------------------------------------------------------------
  # ● 項目数の取得
  #--------------------------------------------------------------------------
  def item_max
    return 2
  end
  #--------------------------------------------------------------------------
  # ● リフレッシュ
  #--------------------------------------------------------------------------  

    
  def refresh
    contents.clear
    change_color(system_color)
    draw_text(0,0,item_width,item_height, "Location")
    change_color(normal_color)
 if     /<マップ名\s*(\S*)\s*>/ =~ $game_map.note
    draw_text(0,24,item_width,item_height, $1)#$game_map.display_name)
  end
    end
  #--------------------------------------------------------------------------
  # ● ウィンドウを開く
  #--------------------------------------------------------------------------
  def open
    refresh
    super
  end
end

#==============================================================================
