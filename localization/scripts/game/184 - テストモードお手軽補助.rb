class Game_CharacterBase
  #--------------------------------------------------------------------------
  # 移動速度の取得（ダッシュを考慮）
  #--------------------------------------------------------------------------
  alias real_move_speed_sup real_move_speed
  def real_move_speed
    
    #マップテストキー5が押されていて、なおかつダッシュ状態ならば
    #更に加速する。
    
    real_move_speed_sup + ((Input.press?(TEST_SUP::MKEY5) && dash?) ? 2 : 0)
  end
end

class Scene_Map
  #--------------------------------------------------------------------------
  # テストモード用のコマンドを有効とするか？
  #--------------------------------------------------------------------------
  def test_key_enable?
    
    #プレイヤーが操作可能であり
    #なおかつテストコマンド用キーを押している場合は有効。
    
    $game_player.movable? && Input.press?(TEST_SUP::TEST)
  end
  #--------------------------------------------------------------------------
  # フレーム更新
  #--------------------------------------------------------------------------
  alias update_sup update
  def update
    
    #イベント実行中ではないか？
    
    unless $game_map.interpreter.running?
      
      #テストモードコマンドが有効か？
      
      if test_key_enable?
        
        #マップテストキー1が押された場合、特定のキーワードのイベントを全て起動。
        
        if Input.trigger?(TEST_SUP::MKEY1)
        $game_map.events.values.each {|event|
          TEST_SUP::EVN_WORD.each {|i| event.start if event.check_test_name}
        }
      end
        
        #マップテストキー2が押された場合、所持金を99999999増加させる。
        
        $game_party.gain_gold(99999999) if Input.trigger?(TEST_SUP::MKEY2)
        
        #マップテストキー3が押された場合、パーティメンバーのEXPを99999999増加させる。
        
        $game_party.members.each {|i| i.change_exp(i.exp + 99999999, true)} if Input.trigger?(TEST_SUP::MKEY3)
        
        #マップテストキー4が押された場合、全てのアイテム/武器/防具を所持限界まで入手する。
        
        if Input.trigger?(TEST_SUP::MKEY4)
          $data_items.each {|item| $game_party.gain_item(item, $game_party.max_item_number(item)) if item && !item.name.empty?}
          $data_weapons.each {|item| $game_party.gain_item(item, $game_party.max_item_number(item)) if item && !item.name.empty?}
          $data_armors.each {|item| $game_party.gain_item(item, $game_party.max_item_number(item)) if item && !item.name.empty?}
        end
      end
    end
    
    #本来の処理を実行。
    
    update_sup
  end
end
class Scene_Battle < Scene_Base
  #--------------------------------------------------------------------------
  # テストモード用のコマンドを有効とするか？
  #--------------------------------------------------------------------------
  def test_key_enable?
    
    #なおかつテストコマンド用キーを押している場合は有効。
    
    Input.press?(TEST_SUP::TEST)
    
  end
  #--------------------------------------------------------------------------
  # フレーム更新
  #--------------------------------------------------------------------------
  alias update_sup update
  def update
    
    #テストモードコマンドが有効か？
    
    if test_key_enable?
      
      #戦闘テストキー1が押された場合、敵全体のHPを0にする。
      
      $game_troop.members.each {|i|
      if i.alive?
        i.hp = 0
        i.perform_collapse_effect if i.dead?
      end
      } if Input.trigger?(TEST_SUP::BKEY1)
      
      #戦闘テストキー2が押された場合、敵全体のHPを全快にする。
      
      $game_troop.members.each {|i| i.hp = i.mhp if i.exist?} if Input.trigger?(TEST_SUP::BKEY2)
      
      #戦闘テストキー3が押された場合、味方全体のHPを0にする。
      
      $game_party.members.each {|i|
      if i.alive?
        i.hp = 0
        i.perform_collapse_effect if i.dead?
      end
      } if Input.trigger?(TEST_SUP::BKEY3)
      
      #戦闘テストキー4が押された場合、味方全体のHPを全快にする。
      
      $game_party.members.each {|i| i.hp = i.mhp if i.exist?} if Input.trigger?(TEST_SUP::BKEY4)
      
      #戦闘テストキー5が押された場合、戦闘を中断する。
      
      BattleManager.abort if Input.trigger?(TEST_SUP::BKEY5)
    end
    
    #本来の処理を実行。
    
    update_sup
  end
end
