#==============================================================================
#   マップ画面で非イベント実行中かつプレイヤーが移動していない状態の場合
#   「CTRLキーを押しつつ」以下のキーを押す事で
#   それぞれ特殊な効果が得られます。
#------------------------------------------------------------------------------
#   F5
#   
#   マップ内の特定ワードを名前に含むイベントを強制起動します。
#------------------------------------------------------------------------------
#   F6
#   
#   所持金が99999999増加します。
#------------------------------------------------------------------------------
#   F7
#
#   メンバー全員のEXPを99999999増加させます。
#------------------------------------------------------------------------------
#   F8
#
#   名前のついている全てのアイテムを入手します。
#==============================================================================
#   戦闘中、「CTRLキーを押しつつ」以下のキーを押す事で
#   それぞれ特殊な効果が得られます。
#------------------------------------------------------------------------------
#   F5
#   
#   敵全体のHPを0にします。
#------------------------------------------------------------------------------
#   F6
#   
#   敵全体のHPを対象の最大HPまで回復します。
#------------------------------------------------------------------------------
#   F7
#   
#   味方全体のHPを0にします。
#------------------------------------------------------------------------------
#   F8
#   
#   味方全体のHPを対象の最大HPまで回復します。
#------------------------------------------------------------------------------
#   F9
#   
#   戦闘を強制的に中断します。（逃走扱いになります）
#==============================================================================
#   それぞれのボタン指定は変更することができます。
#   nilを指定することで無効化することもできます。
#==============================================================================
module TEST_SUP
  
  #強制起動するイベントの名前に含まれる文字列を設定します。
  #複数設定する場合は["宝箱", "小さなメダル"]等、「,」で区切ってください。
  #文字列は「""」で囲う事も忘れずに。

  EVN_WORD = ["宝箱"]
  
  #マップ/戦闘共通で、テストコマンドを有効にする為に
  #押しておくボタンを指定します。
  
  TEST  = :CTRL
  
  #マップ画面で、マップ内の特定ワードを名前に含むイベントを強制起動するボタンを指定します。
  
  MKEY1 = :F5
  
  #マップ画面で、所持金が99999999増加するボタンを指定します。
  
  MKEY2 = :F6
  
  #マップ画面で、メンバー全員のEXPを99999999増加させるボタンを指定します。
  
  MKEY3 = :F7
  
  #マップ画面で、名前のついている全てのアイテムを入手するボタンを指定します。
  
  MKEY4 = :F8
  
  MKEY5 = :F10
  
  #マップ画面で、ダッシュ速度を更に加速させるボタンを指定します。
  
  MKEY5 = :ALT
  
  #戦闘中、敵全体のHPを0にするボタンを指定します。
  
  BKEY1 = :F5
  
  #戦闘中、敵全体のHPを対象の最大HPまで回復するボタンを指定します。
  
  BKEY2 = :F6
  
  #戦闘中、味方全体のHPを0にするボタンを指定します。
  
  BKEY3 = :F7
  
  #戦闘中、味方全体のHPを対象の最大HPまで回復するボタンを指定します。
  
  BKEY4 = :F8
  
  #戦闘中、戦闘を強制的に中断するボタンを指定します。（逃走扱いになります）
  
  BKEY5 = :F9
  
end
#テストモードか戦闘テストモードの場合のみ全ての処理を実行。

class RPG::Event
  #--------------------------------------------------------------------------
  # 強制起動の対象となるか否かを設定
  #--------------------------------------------------------------------------
  def check_test_name
    
    #キャッシュが存在する場合はキャッシュを返す。
    
    return @check_test_name if @check_test_name != nil
    
    #とりあえずfalseにする。
    
    @check_test_name = false
    
    #名前に該当するキーワードが含まれている場合はtrueにする。
    
    TEST_SUP::EVN_WORD.each {|word|
      @check_test_name = true if self.name.include?(word)
    }
    
    #データを返す。
    
    @check_test_name
  end
end
